using System.Text;
using System.Text.Json;
using MsSqlOperator.Configuration;

namespace MsSqlOperator.Operator.Codegen;

/// <summary>
/// Regenerates <c>SqlServerPublishedTags.g.cs</c> from the registry's own tag list:
/// <c>dotnet run -- refresh-images [output-file]</c>.
///
/// The operator has to know which tags actually exist, because the tag it would otherwise build by
/// convention is frequently not the tag Microsoft published — SQL Server 2022 has no
/// <c>2022-CU1-ubuntu-22.04</c> (Ubuntu 22.04 only starts at CU10, and CU1 is spelled
/// <c>2022-RTM-CU1</c>), and SQL Server 2025 has no <c>2025-RTM-ubuntu-24.04</c> outside of a preview
/// tag. Guessing those produces an ImagePullBackOff hours after an apply that admission had cheerfully
/// accepted; a snapshot of the registry turns them into a rejection at apply time.
///
/// This runs by hand (or on a schedule), never at reconcile: the admission path must not depend on
/// the registry being reachable.
/// </summary>
public static class ImageCatalogRefresher
{
    private const string TagsUrl = "https://mcr.microsoft.com/v2/mssql/server/tags/list";

    private const string DefaultOutput = "src/MsSqlOperator/Configuration/SqlServerPublishedTags.g.cs";

    public static async Task<int> RunAsync(string[] args, CancellationToken ct = default)
    {
        var output = args.Length > 1 ? args[1] : FindDefaultOutput();
        var today = DateTime.UtcNow.ToString("yyyy-MM-dd");

        using var http = new HttpClient();
        var json = await http.GetStringAsync(TagsUrl, ct);
        var tags = JsonDocument.Parse(json).RootElement.GetProperty("tags")
            .EnumerateArray()
            .Select(tag => tag.GetString())
            .OfType<string>()
            // Only the tags this operator claims to understand: a supported major version, and a build
            // the parser can read (CTP/RC/GA/latest are none of our business).
            .Where(tag => SqlServerImages.SupportedVersions.Any(v => tag.StartsWith($"{v}-", StringComparison.Ordinal))
                          && SqlServerBuild.TryParseTag(tag, out _))
            .OrderBy(tag => tag, StringComparer.Ordinal)
            .ToList();

        if (tags.Count == 0)
            throw new InvalidOperationException($"{TagsUrl} returned no usable tag — refusing to write an empty catalogue.");

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"// Snapshot of the tags {SqlServerImages.DefaultRepository} publishes, taken {today}.");
        sb.AppendLine("// Regenerate with: dotnet run --project src/MsSqlOperator -- refresh-images");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("namespace MsSqlOperator.Configuration;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>What the registry actually publishes — see <see cref=\"SqlServerImages\"/>.</summary>");
        sb.AppendLine("internal static class SqlServerPublishedTags");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string SnapshotDate = \"{today}\";");
        sb.AppendLine();
        sb.AppendLine("    public static readonly string[] Tags =");
        sb.AppendLine("    [");
        foreach (var tag in tags)
            sb.AppendLine($"        \"{tag}\",");
        sb.AppendLine("    ];");
        sb.AppendLine("}");

        await File.WriteAllTextAsync(output, sb.ToString(), ct);
        Console.WriteLine($"{tags.Count} published tags written to {output} (snapshot {today})");
        return 0;
    }

    /// <summary>The snapshot, looked up from the current directory upwards. <c>dotnet run --project
    /// src/MsSqlOperator</c> starts the process in the project directory (the Web SDK sets
    /// <c>RunWorkingDirectory</c>), so the repository-relative default resolved against the current
    /// directory pointed at <c>src/MsSqlOperator/src/MsSqlOperator/…</c> — every scheduled refresh
    /// failed on it.</summary>
    private static string FindDefaultOutput()
    {
        for (var dir = new DirectoryInfo(Environment.CurrentDirectory); dir is not null; dir = dir.Parent)
        {
            var candidate = Path.Combine(dir.FullName, DefaultOutput);
            if (File.Exists(candidate))
                return candidate;
        }

        throw new InvalidOperationException(
            $"{DefaultOutput} not found from {Environment.CurrentDirectory} or any parent: pass the output file explicitly.");
    }
}
